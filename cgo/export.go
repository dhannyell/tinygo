package cgo

// This file generates _cgo_export.h, the header that C files in a package
// include to call the Go functions marked with //export.

import (
	"go/ast"
	"strings"
)

// exportHeaderProlog declares the Go types that exported functions can use.
const exportHeaderProlog = `typedef signed char GoInt8;
typedef unsigned char GoUint8;
typedef short GoInt16;
typedef unsigned short GoUint16;
typedef int GoInt32;
typedef unsigned int GoUint32;
typedef long long GoInt64;
typedef unsigned long long GoUint64;
typedef __PTRDIFF_TYPE__ GoInt;
typedef __SIZE_TYPE__ GoUint;
typedef __SIZE_TYPE__ GoUintptr;
typedef float GoFloat32;
typedef double GoFloat64;
`

// exportGoTypes maps Go types to the C types of exportHeaderProlog.
var exportGoTypes = map[string]string{
	"int8": "GoInt8", "uint8": "GoUint8", "byte": "GoUint8", "bool": "GoUint8",
	"int16": "GoInt16", "uint16": "GoUint16",
	"int32": "GoInt32", "uint32": "GoUint32", "rune": "GoInt32",
	"int64": "GoInt64", "uint64": "GoUint64",
	"int": "GoInt", "uint": "GoUint", "uintptr": "GoUintptr",
	"float32": "GoFloat32", "float64": "GoFloat64",
}

// exportCNames maps the short cgo names of C types to their C spelling.
var exportCNames = map[string]string{
	"schar": "signed char", "uchar": "unsigned char", "ushort": "unsigned short",
	"uint": "unsigned int", "ulong": "unsigned long",
	"longlong": "long long", "ulonglong": "unsigned long long",
}

// exportHeader returns the text of _cgo_export.h, or "" if no function in
// files has an //export line. Like in Go, the header contains the preamble of
// each file with an //export line, so that preamble must only declare.
func (p *cgoPackage) exportHeader(files []*ast.File) string {
	var preambles, prototypes strings.Builder
	for i, f := range files {
		hasExport := false
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || fn.Doc == nil {
				continue
			}
			for _, comment := range fn.Doc.List {
				name, ok := strings.CutPrefix(comment.Text, "//export ")
				if !ok {
					continue
				}
				hasExport = true
				prototypes.WriteString(exportPrototype(strings.TrimSpace(name), fn.Type))
			}
		}
		if hasExport {
			preambles.WriteString(p.cgoHeaders[i])
			preambles.WriteString("\n")
		}
	}
	if prototypes.Len() == 0 {
		return ""
	}
	return "/* Code generated by TinyGo. DO NOT EDIT. */\n\n" +
		"#ifndef TINYGO_CGO_EXPORT_H\n#define TINYGO_CGO_EXPORT_H\n\n" +
		exportHeaderProlog + "\n" +
		preambles.String() +
		"\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n" +
		prototypes.String() +
		"\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n"
}

// exportPrototype returns the C prototype of an exported function. A function
// with a type that has no C form gets a comment instead.
func exportPrototype(name string, fn *ast.FuncType) string {
	result := "void"
	if fn.Results != nil && len(fn.Results.List) != 0 {
		if len(fn.Results.List) != 1 || len(fn.Results.List[0].Names) > 1 {
			return "/* " + name + ": more than one result */\n"
		}
		typ, ok := exportCType(fn.Results.List[0].Type)
		if !ok {
			return "/* " + name + ": unsupported result type */\n"
		}
		result = typ
	}
	var params []string
	for _, field := range fn.Params.List {
		typ, ok := exportCType(field.Type)
		if !ok {
			return "/* " + name + ": unsupported parameter type */\n"
		}
		if len(field.Names) == 0 {
			params = append(params, typ)
		}
		for _, ident := range field.Names {
			params = append(params, typ+" "+ident.Name)
		}
	}
	if len(params) == 0 {
		params = []string{"void"}
	}
	return "extern " + result + " " + name + "(" + strings.Join(params, ", ") + ");\n"
}

// exportCType returns the C spelling of a parameter or result type.
func exportCType(expr ast.Expr) (string, bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		typ, ok := exportGoTypes[t.Name]
		return typ, ok
	case *ast.StarExpr:
		if elem, ok := exportCType(t.X); ok {
			return elem + "*", true
		}
		// The C side cannot name a Go type, but the pointer has the same ABI.
		return "void*", true
	case *ast.SelectorExpr:
		x, ok := t.X.(*ast.Ident)
		if !ok {
			return "", false
		}
		if x.Name == "unsafe" && t.Sel.Name == "Pointer" {
			return "void*", true
		}
		if x.Name != "C" {
			return "", false
		}
		name := t.Sel.Name
		if c, ok := exportCNames[name]; ok {
			return c, true
		}
		for _, prefix := range []string{"struct_", "union_", "enum_"} {
			if rest, ok := strings.CutPrefix(name, prefix); ok {
				return prefix[:len(prefix)-1] + " " + rest, true
			}
		}
		return name, true
	}
	return "", false
}
